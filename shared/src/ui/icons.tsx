export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  size?: number;
  /** Accessible name. Omit for decorative icons (the usual case: label the button instead). */
  title?: string;
}

export type IconComponent = (props: IconProps) => ReactElement;

function createIcon(displayName: string, body: ReactNode): IconComponent {
  function Icon({ size = 20, title, strokeWidth = 1.75, ...rest }: IconProps) {
    const a11y = title
      ? ({ role: "img", "aria-label": title } as const)
      : ({ "aria-hidden": true, focusable: false } as const);
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        {...a11y}
        {...rest}
      >
        {title ? <title>{title}</title> : null}
        {body}
      </svg>
    );
  }
  Icon.displayName = `Icon${displayName}`;
  return Icon;
}

